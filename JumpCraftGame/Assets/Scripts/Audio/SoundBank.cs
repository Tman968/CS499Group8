using System.Collections.Generic;
using UnityEngine;

/// <summary>Which part of the mix a sound belongs to. Each bus is compressed and ducked as a group.</summary>
public enum Bus
{
    /// <summary>The wizard's own actions: wands, steps, jumps. The player's sounds take precedence.</summary>
    Player,
    /// <summary>Skeletons and their bones. Ducked under the player's attacks.</summary>
    Enemy,
    /// <summary>Elements hitting things, reactions, props and hazards. Ducked under the player's attacks.</summary>
    World,
    /// <summary>Menus, pickups and fanfares. Never spatial, never ducked.</summary>
    UI,
}

/// <summary>How one sound is played and mixed. The clips themselves come from Resources/Audio.</summary>
public class SoundDef
{
    public string name;
    public Bus bus;
    public float volume = 1f;
    /// <summary>Random pitch spread either side of 1, so repeats don't sound mechanical.</summary>
    public float pitchJitter = 0.04f;
    /// <summary>How many of this sound may play at once; the oldest is cut off to make room.</summary>
    public int maxVoices = 4;
    /// <summary>Seconds that must pass before this sound can start again.</summary>
    public float cooldown = 0.02f;
    /// <summary>When the voice pool is full, higher-priority sounds take voices from lower ones.</summary>
    public int priority = 50;
    /// <summary>Foreground sounds (the player's attacks) duck the Enemy and World buses, the ambience and the music.</summary>
    public bool foreground;
    /// <summary>Played at the listener, ignoring world position.</summary>
    public bool flat;
    /// <summary>How far past the edge of the screen it can still be heard, in screen half-widths.</summary>
    public float reach = 1.2f;
    // Loops only: how fast they fade in and out (seconds).
    public bool loop;
    public float attack = 0.08f;
    public float release = 0.25f;

    public AudioClip[] clips = System.Array.Empty<AudioClip>();
    internal float lastPlayed = -999f;
    internal float heat;   // recent plays, decaying: rapid repeats get quieter
    internal int lastClip = -1;

    public AudioClip PickClip()
    {
        if (clips.Length == 0) return null;
        if (clips.Length == 1) return clips[0];
        // Never the same variant twice in a row.
        var i = Random.Range(0, clips.Length - 1);
        if (i >= lastClip) i++;
        lastClip = i;
        return clips[i];
    }
}

/// <summary>
/// Every sound in the game and how it sits in the mix. The clips are generated by
/// Tools/generate_sounds.py into Resources/Audio; a clip named name_N is a variant of name.
/// A clip with no entry here still plays, on the World bus with default settings.
/// </summary>
public static class SoundBank
{
    static Dictionary<string, SoundDef> defs;

    public static SoundDef Get(string name)
    {
        if (defs == null) Load();
        return defs.TryGetValue(name, out var d) ? d : null;
    }

    static void Load()
    {
        defs = new Dictionary<string, SoundDef>();
        Define();

        // Group the clips by name (dropping a trailing _<number>), in order.
        var groups = new Dictionary<string, List<AudioClip>>();
        foreach (var clip in Resources.LoadAll<AudioClip>("Audio"))
        {
            var name = clip.name;
            var cut = name.LastIndexOf('_');
            if (cut > 0 && int.TryParse(name.Substring(cut + 1), out _)) name = name.Substring(0, cut);
            if (!groups.TryGetValue(name, out var list)) groups[name] = list = new List<AudioClip>();
            list.Add(clip);
        }
        foreach (var pair in groups)
        {
            pair.Value.Sort((a, b) => string.CompareOrdinal(a.name, b.name));
            if (!defs.TryGetValue(pair.Key, out var def)) defs[pair.Key] = def = new SoundDef { name = pair.Key, bus = Bus.World };
            def.clips = pair.Value.ToArray();
        }
    }

    static SoundDef D(string name, Bus bus, float volume, int maxVoices = 4, float cooldown = 0.02f, int priority = 50)
    {
        var d = new SoundDef { name = name, bus = bus, volume = volume, maxVoices = maxVoices, cooldown = cooldown, priority = priority };
        defs[name] = d;
        return d;
    }

    static SoundDef Loop(string name, Bus bus, float volume, float attack = 0.08f, float release = 0.3f)
    {
        var d = D(name, bus, volume, 8, 0f, 70);
        d.loop = true;
        d.attack = attack;
        d.release = release;
        d.pitchJitter = 0f;
        return d;
    }

    static void Define()
    {
        // ---------------------------------------------------------------- the wizard
        foreach (var s in new[] { "step_stone", "step_ice", "step_water", "step_embers" })
            D(s, Bus.Player, 0.5f, 2, 0.07f, 30).pitchJitter = 0.08f;
        D("jump", Bus.Player, 0.55f, 2, 0.1f, 60).pitchJitter = 0.06f;
        D("land", Bus.Player, 0.5f, 2, 0.12f, 50);
        D("land_heavy", Bus.Player, 0.7f, 1, 0.2f, 60);
        var hurt = D("hurt", Bus.Player, 0.9f, 2, 0.15f, 95);
        hurt.foreground = true;
        var death = D("death", Bus.Player, 1f, 1, 1f, 100);
        death.foreground = true;
        death.flat = true;
        Loop("heartbeat", Bus.Player, 0.6f, 0.6f, 0.8f).flat = true;

        // ---------------------------------------------------------------- wands
        foreach (var e in new[] { "fire", "ice", "lightning", "wind" })
        {
            D($"wand_swap_{e}", Bus.Player, 0.55f, 1, 0.05f, 70).flat = true;
            var start = D($"wand_{e}_start", Bus.Player, 0.85f, 2, 0.08f, 90);
            start.foreground = true;
            var loop = Loop($"wand_{e}_loop", Bus.Player, 0.75f, 0.06f, 0.18f);
            loop.foreground = true;
            loop.priority = 90;
            D($"wand_{e}_end", Bus.Player, 0.6f, 2, 0.08f, 70);
            var backfire = D($"backfire_{e}", Bus.Player, 1f, 1, 0.5f, 100);
            backfire.foreground = true;
        }
        D("wand_empty", Bus.Player, 0.6f, 1, 0.2f, 60).flat = true;
        D("wand_ready", Bus.Player, 0.45f, 2, 0.1f, 60).flat = true;

        // ---------------------------------------------------------------- the elements meeting things
        D("fire_hit", Bus.World, 0.35f, 3, 0.09f, 20);
        D("ice_hit", Bus.World, 0.4f, 4, 0.045f, 25).pitchJitter = 0.1f;
        D("ice_shatter", Bus.World, 0.8f, 3, 0.08f, 75);
        D("frost_form", Bus.World, 0.3f, 2, 0.18f, 15);
        D("zap_hit", Bus.World, 0.55f, 3, 0.07f, 55);
        D("zap_air", Bus.World, 0.3f, 2, 0.1f, 15);
        D("ignite", Bus.World, 0.6f, 3, 0.1f, 60);
        Loop("burn_loop", Bus.World, 0.45f, 0.2f, 0.5f);
        D("freeze", Bus.World, 0.7f, 3, 0.1f, 75);
        D("thaw", Bus.World, 0.55f, 2, 0.1f, 50);
        D("shock", Bus.World, 0.5f, 3, 0.15f, 55);
        D("steam_puff", Bus.World, 0.4f, 2, 0.15f, 30);

        // ---------------------------------------------------------------- reactions
        D("steam_boom", Bus.World, 1f, 2, 0.2f, 85).reach = 2f;
        Loop("steam_loop", Bus.World, 0.5f, 0.3f, 1f);
        D("plasma_boom", Bus.World, 1f, 2, 0.2f, 85).reach = 2f;
        Loop("plasma_loop", Bus.World, 0.55f, 0.1f, 0.4f);
        D("vortex_start", Bus.World, 0.85f, 2, 0.3f, 80).reach = 2f;
        Loop("vortex_loop", Bus.World, 0.6f, 0.3f, 0.8f);
        D("blizzard_start", Bus.World, 0.8f, 2, 0.3f, 80).reach = 2f;
        Loop("blizzard_loop", Bus.World, 0.55f, 0.4f, 1f);
