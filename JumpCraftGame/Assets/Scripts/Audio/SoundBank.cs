        Loop("electric_hum_loop", Bus.World, 0.35f, 0.15f, 0.4f);
        D("storm_start", Bus.World, 1f, 1, 0.5f, 90).reach = 2.5f;
        Loop("storm_loop", Bus.World, 0.6f, 0.4f, 1f).reach = 2f;
        D("thunder", Bus.World, 0.85f, 2, 0.35f, 80).reach = 2.5f;

        // ---------------------------------------------------------------- skeletons
        var step = D("skel_step", Bus.Enemy, 0.35f, 3, 0.05f, 20);
        step.pitchJitter = 0.1f;
        step.reach = 0.6f;
        D("skel_throw", Bus.Enemy, 0.6f, 3, 0.1f, 65);
        D("skel_hurt", Bus.Enemy, 0.65f, 3, 0.12f, 65);
        D("skel_death", Bus.Enemy, 0.8f, 3, 0.1f, 80);
        D("skel_alert", Bus.Enemy, 0.55f, 2, 0.6f, 60);
        // A bone striking the wizard is about the player, so it isn't ducked under the player's sounds.
        D("bone_hit", Bus.Player, 0.9f, 2, 0.1f, 95);
        D("bone_clatter", Bus.Enemy, 0.45f, 4, 0.05f, 35);
        D("bone_deflect", Bus.Enemy, 0.6f, 3, 0.08f, 60);

        // ---------------------------------------------------------------- the world
        D("prop_douse", Bus.World, 0.6f, 2, 0.2f, 55);
        D("prop_burnaway", Bus.World, 0.7f, 2, 0.2f, 55);
        D("pendulum_whoosh", Bus.World, 0.5f, 3, 0.15f, 40).reach = 0.8f;
        D("pendulum_hit", Bus.World, 0.9f, 2, 0.15f, 80);
        D("lift_charge", Bus.World, 0.55f, 2, 0.3f, 50);
        Loop("lift_loop", Bus.World, 0.5f, 0.15f, 0.25f);
        D("lift_stop", Bus.World, 0.6f, 2, 0.3f, 50);

        // ---------------------------------------------------------------- items and the HUD
        foreach (var ui in new[] { "ui_click", "ui_hover", "ui_open", "ui_close", "notify", "pickup", "pickup_rare",
                                   "key_get", "weapon_get", "recipe_get", "craft", "menu_start", "sting_death" })
        {
            var d = D(ui, Bus.UI, 0.6f, 2, 0.04f, 85);
            d.flat = true;
            d.pitchJitter = 0f;
        }
        Get("ui_hover").volume = 0.3f;
        Get("ui_hover").cooldown = 0.05f;
        Get("ui_open").volume = 0.5f;
        Get("ui_close").volume = 0.5f;
        Get("notify").volume = 0.5f;
        Get("pickup").pitchJitter = 0.03f;
        Get("pickup_rare").volume = 0.7f;
        foreach (var big in new[] { "key_get", "weapon_get", "craft", "menu_start", "sting_death" }) Get(big).volume = 0.85f;
        Get("recipe_get").volume = 0.7f;
        D("item_drop", Bus.World, 0.55f, 2, 0.08f, 50);
    }
}
